export function getAllEnquiryServices() {
  return enquiryCategories.flatMap(cat =>
    cat.services.map(svc => ({
      ...svc,
      categoryId: cat.id,
      categoryLabel: cat.label,
      categoryIcon: cat.icon
    }))
  );
}

export function getServicesByCategory(categoryId) {
  const cat = enquiryCategories.find(c => c.id === categoryId);
  return cat ? cat.services : [];
}

export function getCategoryById(categoryId) {
  return enquiryCategories.find(c => c.id === categoryId) || null;
}

